#!/usr/bin/env python3
"""The ×4 oversampler's half-band FIR (Phase 13 step 78, TO_PROJECT_SPEC §13.8): a Kaiser-windowed ideal half-band of
N = 4K − 1 taps — the centre tap 1/2, every other even tap zero by construction, K odd taps a side — printed as
voxo/src/halfband.h with its measured stopband. Pure Python (no numpy): the Kaiser window's I0 by its series.

  python3 tools/halfband_design.py [--taps 39] [--beta 5.65] > voxo/src/halfband.h
"""
import math, sys
taps = 39; beta = 5.65
a = sys.argv[1:]
if "--taps" in a: taps = int(a[a.index("--taps") + 1])
if "--beta" in a: beta = float(a[a.index("--beta") + 1])
assert taps % 4 == 3, "a half-band of N = 4K − 1 taps"
K = (taps + 1) // 4
def i0(x):
    s, t, k = 1.0, 1.0, 1
    while True:
        t *= (x / (2 * k)) ** 2; s += t; k += 1
        if t < 1e-17 * s: return s
M = (taps - 1) // 2
def kaiser(n):   # n in [−M, M]
    return i0(beta * math.sqrt(max(0.0, 1.0 - (n / M) ** 2))) / i0(beta)
def ideal(n):    # the half-band sinc: 0.5 at 0, zero at even n ≠ 0
    return 0.5 if n == 0 else math.sin(math.pi * n / 2) / (math.pi * n)
h = {n: ideal(n) * kaiser(n) for n in range(-M, M + 1)}
# normalise the DC gain to one: the centre 1/2 plus twice the odd taps
odd = [h[n] for n in range(1, M + 1, 2)]
s = 0.5 + 2.0 * sum(odd); odd = [x / s for x in odd]; centre = 0.5 / s
# the response: |H(f)| over the stopband [0.3, 0.5] of the input rate (the alias band the ×4 gate measures: the output's
# 0.2..0.5 of its own rate folds from the input's 0.3..0.5 through the 2:1 stage)
def H(f):
    re = centre
    for k, c in enumerate(odd): n = 2 * k + 1; re += 2.0 * c * math.cos(2 * math.pi * f * n)
    return abs(re)
worst = max(H(0.30 + 0.0005 * i) for i in range(401))
pass_rip = max(abs(1.0 - H(0.0005 * i)) for i in range(401))   # 0 .. 0.2 of the input rate
print("// voxo/src/halfband.h — GENERATED by tools/halfband_design.py (Phase 13 step 78): do not edit.")
print(f"// A Kaiser-windowed half-band FIR, {taps} taps (β {beta}): the centre {centre:.9g}, {K} odd taps a side, every other even tap")
print(f"// zero; DC gain 1. Stopband [0.30, 0.50] of the input rate: worst {20*math.log10(worst):.1f} dB; passband [0, 0.20] ripple {20*math.log10(1+pass_rip):.3f} dB.")
print("// Decimating 2:1, the input's band above 0.30 folds below 0.20 of the output rate at that attenuation — the ×4 gate's band.")
print("#pragma once")
print(f"#define SUZU_HALFBAND_SIDE {K}")
print(f"static const float SUZU_HALFBAND_CENTRE = {centre:.9g}f;")
print("static const float SUZU_HALFBAND_ODD[SUZU_HALFBAND_SIDE] = {   // h[1], h[3], … (symmetric: h[-n] = h[n])")
for k, c in enumerate(odd): print(f"    {c:.9g}f,   // h[±{2*k+1}]")
print("};")
