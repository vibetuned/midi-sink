#!/usr/bin/env python3
"""The Michel-Lévy chart as a lookup table — Kessho's physical palette (v3.0 step 71, DECISIONS_10 #3).

  kessho_lut.py [--out core/src/kessho_lut.h] [--png <chart.png>] [--check]

A birefringent slab of retardation G (nm) between crossed polarizers, at the
full isoclinic brush, transmits I(l) = sin^2(pi G / l) of the backlight at each
wavelength l. The table integrates that transmission against the CIE 1931 2°
colour matching functions (the Wyman–Sloan–Shirley multi-lobe fit, JCGT 2013)
under a 6504 K Planckian backlight (daylight's temperature; the white is
balanced per channel so a fully transmitted spectrum is exactly (1, 1, 1)),
converts XYZ to linear sRGB, clips, and encodes to 8-bit sRGB: 1024 texels
from G = 0 to KESSHO_LUT_NM (2200 nm, the fourth order's end). Pure Python,
no dependencies; the table is deterministic (the header is regenerated
bit-identically from this script).

--check prints the colour at the retardations the chart is known by (the
sensitive tint at ~550 nm, the second-order red at ~1100 nm, the third-order
pink/green pair at ~1650 nm) and the first-order hue sequence (black, grey,
white, yellow, orange, red, violet, blue, blue-green, green), as names
derived from the hue angle — the sanity check of step 71's gate 4 when no
published chart is at hand (a published chart's sampled colours replace it
when the author has one; DECISIONS_10 #3).
"""
import argparse, math, struct, sys

N = 1024
G_MAX = 2200.0          # nm
L0, L1, DL = 380.0, 780.0, 2.0   # the wavelength grid, nm

def g(l, mu, s1, s2):
    s = s1 if l < mu else s2
    t = (l - mu) / s
    return math.exp(-0.5 * t * t)

def cmf(l):   # Wyman, Sloan & Shirley (2013), the multi-lobe piecewise-Gaussian fit of CIE 1931 2°
    x = 1.056 * g(l, 599.8, 37.9, 31.0) + 0.362 * g(l, 442.0, 16.0, 26.7) - 0.065 * g(l, 501.1, 20.4, 26.2)
    y = 0.821 * g(l, 568.8, 46.9, 40.5) + 0.286 * g(l, 530.9, 16.3, 31.1)
    z = 1.217 * g(l, 437.0, 11.8, 36.0) + 0.681 * g(l, 459.0, 26.0, 13.8)
    return x, y, z

def planck(l_nm, T=6504.0):
    l = l_nm * 1e-9
    c1, c2 = 3.741771e-16, 1.438776877e-2
    return c1 / (l ** 5) / (math.exp(c2 / (l * T)) - 1.0)

XYZ_TO_RGB = ((3.2404542, -1.5371385, -0.4985314),
              (-0.9692660, 1.8760108, 0.0415560),
              (0.0556434, -0.2040259, 1.0572252))

def xyz_to_rgb(X, Y, Z):
    return tuple(m[0] * X + m[1] * Y + m[2] * Z for m in XYZ_TO_RGB)

def srgb8(c):
    c = min(max(c, 0.0), 1.0)
    e = 12.92 * c if c <= 0.0031308 else 1.055 * (c ** (1.0 / 2.4)) - 0.055
    return int(round(e * 255.0))

waves = [L0 + i * DL for i in range(int((L1 - L0) / DL) + 1)]
S = [planck(l) for l in waves]
CM = [cmf(l) for l in waves]

def integrate(transmit):
    X = Y = Z = 0.0
    for s, (x, y, z), t in zip(S, CM, transmit):
        X += s * x * t; Y += s * y * t; Z += s * z * t
    return X, Y, Z

white = xyz_to_rgb(*integrate([1.0] * len(waves)))   # the backlight itself, for the per-channel balance

def colour(G):
    X, Y, Z = integrate([math.sin(math.pi * G / l) ** 2 for l in waves])
    r, gg, b = xyz_to_rgb(X, Y, Z)
    return (r / white[0], gg / white[1], b / white[2])   # linear, white-balanced: full transmission = (1, 1, 1)

def hue_name(rgb):
    r, gg, b = rgb
    mx, mn = max(rgb), min(rgb)
    if mx < 0.08: return "black"
    sat = (mx - mn) / mx
    if sat < 0.12: return "white" if mx > 0.6 else "grey"
    if mx == r: h = (gg - b) / (mx - mn) % 6.0
    elif mx == gg: h = (b - r) / (mx - mn) + 2.0
    else: h = (r - gg) / (mx - mn) + 4.0
    h *= 60.0
    names = [(15, "red"), (45, "orange"), (70, "yellow"), (150, "green"), (195, "blue-green"), (255, "blue"), (290, "violet"), (330, "magenta"), (361, "red")]
    for lim, nm in names:
        if h < lim: return nm
    return "red"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    ap.add_argument("--png", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    table = [colour(G_MAX * i / (N - 1)) for i in range(N)]
    bytes8 = [(srgb8(c[0]), srgb8(c[1]), srgb8(c[2])) for c in table]
    if a.check:
        print("retardation -> linear rgb (white-balanced), 8-bit sRGB, hue")
        for G in (0, 100, 200, 275, 350, 450, 530, 550, 575, 650, 750, 850, 950, 1050, 1100, 1150, 1250, 1350, 1500, 1650, 1750, 2000, 2200):
            c = colour(G); e = tuple(srgb8(x) for x in c)
            print("  %5d nm  (%.3f %.3f %.3f)  #%02x%02x%02x  %s" % (G, c[0], c[1], c[2], e[0], e[1], e[2], hue_name(c)))
        print("white balance of the 6504 K backlight (linear rgb before balance):", tuple(round(x, 4) for x in white))
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write("// kessho_lut.h — GENERATED by tools/kessho_lut.py (v3.0 step 71, DECISIONS_10 #3). Do not edit.\n")
            f.write("// The Michel-Lévy chart: %d texels of 8-bit sRGB from retardation 0 to KESSHO_LUT_NM nm — a slab between\n" % N)
            f.write("// crossed polarizers at the full brush, sin^2(pi G / lambda) integrated against the CIE 1931 2-degree\n")
            f.write("// matching functions (the Wyman–Sloan–Shirley fit) under a 6504 K Planckian backlight, white-balanced.\n")
            f.write("#pragma once\n#include <stdint.h>\n#define KESSHO_LUT_N %d\n#define KESSHO_LUT_NM %.1ff\n" % (N, G_MAX))
            f.write("static const uint8_t KESSHO_LUT_SRGB[KESSHO_LUT_N * 3] = {\n")
            for i in range(0, N, 8):
                row = bytes8[i:i + 8]
                f.write("    " + ", ".join("%3d,%3d,%3d" % t for t in row) + ",\n")
            f.write("};\n")
        print("wrote", a.out)
    if a.png:
        try:
            from PIL import Image
            H = 64
            im = Image.new("RGB", (N, H))
            px = im.load()
            for x in range(N):
                for y in range(H): px[x, y] = bytes8[x]
            im.save(a.png)
            print("wrote", a.png)
        except ImportError:
            print("PIL not available: no PNG", file=sys.stderr)

if __name__ == "__main__":
    main()
